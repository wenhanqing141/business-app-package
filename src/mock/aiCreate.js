// ---------- 蓝图 MD 生成（单一来源：右栏渲染与「下载文档」共用） ----------
function renderAppTable() {
  const lines = ['| 分组 | 应用 | 类型 | 是否自动创建 |', '| --- | --- | --- | --- |']
  AI_SCENE.groups.forEach((g) => {
    g.apps.forEach((a, i) => {
      const auto = a.kind === 'auto' ? '是（表单 / 审批 / 仪表盘）' : '否（计入待完成任务文档）'
      lines.push(`| ${i === 0 ? g.name : ''} | ${a.name} | ${ENGINE_META[a.engine].label} | ${auto} |`)
    })
  })
  return lines.join('\n')
}

